// tl_tests - the runner. Spec: docs/TESTING.md §1, §9.1 (completed by the W1 runner+driver
// lane). Tests are not sim code: printf-class io, clock, filesystem and (read as included by the
// same exemption - the isolate pool cannot exist otherwise, docs/TESTING.md §9.1) process spawn
// are the exemption of docs/TESTING.md §8 R-2.
//
// The pure decisions (glob, tags, suite, seed, verdicts, exit codes) live in runner_core.h so
// they have tests (tests/runner/runner_core.test.cpp); this TU is the io, the process handling
// and the report.
//
// NO SILENT GREEN (W1 runner review 1, docs/TESTING.md §1 - the harness is the only determinism
// safety net, so every way it can report success without having checked anything is a defect):
//   - a selection that matches zero tests is an ERROR, not a clean run;
//   - a selected test that never produced a verdict is an ERROR;
//   - a test that recorded zero checks is a FAIL (TL_SKIP is how a body legitimately runs none);
//   - a child that never spawned is a FAIL, including for a fatal-expected test.
