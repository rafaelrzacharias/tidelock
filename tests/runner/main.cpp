static const u32 TEST_COUNT = (u32)(sizeof(TL_TESTS) / sizeof(TL_TESTS[0]));
static const int EXIT_FAIL = 1;   // a real test failure
// Exit code 2 is the exit-2+marker contract's reserved fatal code (docs/TESTING.md §9.1); tl_fatal
// does not produce it yet (tl_test.h TL_TEST_EXPECT_FATAL doc comment) so nothing here emits it.

void tl_test_fail(TestCtx* t, const char* file, u32 line, const char* expr, bool soft) {
    ++t->failures;
    if (soft) { ++t->soft_failures; }
    fprintf(stderr, "%s:%u: FAIL [%s] %s\n", file, line, t->name, expr);
}

// --- tiny glob: '*' any run, '?' one char. No character classes (docs/TESTING.md §1). --------
static bool glob_match(const char* pat, const char* s) {
    const char* star = nullptr;
    const char* mark = nullptr;
    while (*s) {
        if (*pat == '?' || *pat == *s) { ++pat; ++s; }
        else if (*pat == '*') { star = pat++; mark = s; }
        else if (star) { pat = star + 1; s = ++mark; }
        else { return false; }
    }
    while (*pat == '*') { ++pat; }
    return *pat == 0;
}

// True if `tags` (comma-separated) contains exactly `tag`.
static bool has_tag(const char* tags, const char* tag) {
    const usize n = strlen(tag);
    for (const char* p = tags; *p;) {
        const char* end = strchr(p, ',');
        const usize len = end ? (usize)(end - p) : strlen(p);
        if (len == n && strncmp(p, tag, n) == 0) { return true; }
        if (!end) { break; }
        p = end + 1;
    }
    return false;
}

struct Selection {
    const char* filter;
    const char* include[16];
    u32 include_count;
    const char* exclude[16];
    u32 exclude_count;
};

static bool selected(const TestInfo& ti, const Selection& sel) {
    if (sel.filter && !glob_match(sel.filter, ti.name)) { return false; }
    for (u32 i = 0; i < sel.exclude_count; ++i) {
        if (has_tag(ti.tags, sel.exclude[i])) { return false; }
    }
    for (u32 i = 0; i < sel.include_count; ++i) {
        if (!has_tag(ti.tags, sel.include[i])) { return false; }
    }
    return true;
}

// Suite = the last directory of the test file ("tests/foundation/x.test.cpp" -> "foundation").
// A file with no directory part is its own suite.
static void suite_of(const TestInfo& ti, char* out, usize cap) {
    const char* last = nullptr;
    const char* prev = nullptr;
    for (const char* q = ti.file; *q; ++q) {
        if (*q == '/' || *q == '\\') { prev = last; last = q; }
    }
    const char* begin = last ? (prev ? prev + 1 : ti.file) : ti.file;
    usize n = last ? (usize)(last - begin) : strlen(ti.file);
    if (n >= cap) { n = cap - 1; }
    memcpy(out, begin, n);
    out[n] = 0;
}

// A seed that is a pure function of (--seed, test index) - deterministic, never wall-clock
// (docs/TESTING.md §1 property tests).
static u32 seed_for(u32 global_seed, u32 index) {
    u32 h = global_seed ^ 0x9e3779b9u;
    h ^= index * 0x85ebca6bu;
    h ^= h >> 13; h *= 0xc2b2ae35u; h ^= h >> 16;
    return h;
}

// --- process spawn: one child per test, always via `<self> --run-one <index>` -----------------
// docs/TESTING.md §9.1: --isolate re-executes the parent on a worker pool of core_count
// processes; a TL_TEST_EXPECT_FATAL test always runs in its own child (isolate or not), since a
// real trap must not take down the runner process itself.

struct ChildResult {
    bool spawned;
    bool abnormal;   // terminated other than via a normal return from main() (crash/signal/trap)
    int  exit_code;  // meaningful only when !abnormal
};

#if defined(_WIN32)

static bool make_dir(const char* path) {
    return CreateDirectoryA(path, nullptr) != 0 || GetLastError() == ERROR_ALREADY_EXISTS;
}

static u32 core_count(void) {
    SYSTEM_INFO si; GetSystemInfo(&si);
    return si.dwNumberOfProcessors ? (u32)si.dwNumberOfProcessors : 1u;
}

static void self_path(char* out, usize cap) {
    DWORD n = GetModuleFileNameA(nullptr, out, (DWORD)cap);
    if (n == 0 || n >= cap) { out[0] = 0; }
}

struct ActiveChild { HANDLE process; u32 job_index; bool used; };

// Blocking single spawn+wait (serial path: non-isolate fatal tests, and the failure replay).
static void spawn_and_wait(const char* self, u32 test_index, const char* cwd, ChildResult* out) {
    char cmd[2048];
    snprintf(cmd, sizeof(cmd) - 1, "\"%s\" --run-one %u", self, test_index);
    cmd[sizeof(cmd) - 1] = 0;
    STARTUPINFOA si; memset(&si, 0, sizeof(si)); si.cb = sizeof(si);
    PROCESS_INFORMATION pi; memset(&pi, 0, sizeof(pi));
    out->spawned = CreateProcessA(nullptr, cmd, nullptr, nullptr, FALSE, 0, nullptr, cwd, &si, &pi) != 0;
    if (!out->spawned) { out->abnormal = true; out->exit_code = -1; return; }
    WaitForSingleObject(pi.hProcess, INFINITE);
    DWORD code = 0;
    GetExitCodeProcess(pi.hProcess, &code);
    CloseHandle(pi.hThread);
    CloseHandle(pi.hProcess);
    out->exit_code = (int)code;
    out->abnormal = (code >= 0x80000000u);   // NTSTATUS-shaped: an unhandled exception/trap
}

// Non-blocking spawn for the parallel pool; returns the process HANDLE (or nullptr on failure).
static HANDLE spawn_async(const char* self, u32 test_index, const char* cwd) {
    char cmd[2048];
    snprintf(cmd, sizeof(cmd) - 1, "\"%s\" --run-one %u", self, test_index);
    cmd[sizeof(cmd) - 1] = 0;
    STARTUPINFOA si; memset(&si, 0, sizeof(si)); si.cb = sizeof(si);
    PROCESS_INFORMATION pi; memset(&pi, 0, sizeof(pi));
    if (!CreateProcessA(nullptr, cmd, nullptr, nullptr, FALSE, 0, nullptr, cwd, &si, &pi)) { return nullptr; }
    CloseHandle(pi.hThread);
    return pi.hProcess;
}

static ChildResult reap(HANDLE h) {
    ChildResult r; r.spawned = true;
    DWORD code = 0;
    GetExitCodeProcess(h, &code);
    CloseHandle(h);
    r.exit_code = (int)code;
    r.abnormal = (code >= 0x80000000u);
    return r;
}

#else  // POSIX

static bool make_dir(const char* path) {
    return mkdir(path, 0755) == 0 || errno == EEXIST;
}

static u32 core_count(void) {
    long n = sysconf(_SC_NPROCESSORS_ONLN);
    return n > 0 ? (u32)n : 1u;
}

static void self_path(char* out, usize cap) {
    ssize_t n = readlink("/proc/self/exe", out, cap - 1);
    if (n <= 0) { out[0] = 0; return; }
    out[n] = 0;
}

static void spawn_and_wait(const char* self, u32 test_index, const char* cwd, ChildResult* out) {
    char idx[16];
    snprintf(idx, sizeof(idx), "%u", test_index);
    pid_t pid = fork();
    if (pid < 0) { out->spawned = false; out->abnormal = true; out->exit_code = -1; return; }
    if (pid == 0) {
        if (cwd) { if (chdir(cwd) != 0) { _exit(127); } }
        char* argv[] = { (char*)self, (char*)"--run-one", idx, nullptr };
        execv(self, argv);
        _exit(127);   // execv failed
    }
    int status = 0;
    waitpid(pid, &status, 0);
    out->spawned = true;
    if (WIFEXITED(status)) { out->exit_code = WEXITSTATUS(status); out->abnormal = false; }
    else { out->exit_code = -1; out->abnormal = true; }   // signalled (e.g. SIGILL from __builtin_trap)
}

static pid_t spawn_async_pid(const char* self, u32 test_index, const char* cwd) {
    char idx[16];
    snprintf(idx, sizeof(idx), "%u", test_index);
    pid_t pid = fork();
    if (pid < 0) { return -1; }
    if (pid == 0) {
        if (cwd) { if (chdir(cwd) != 0) { _exit(127); } }
        char* argv[] = { (char*)self, (char*)"--run-one", idx, nullptr };
        execv(self, argv);
        _exit(127);
    }
    return pid;
}

static ChildResult reap_status(int status) {
    ChildResult r; r.spawned = true;
    if (WIFEXITED(status)) { r.exit_code = WEXITSTATUS(status); r.abnormal = false; }
    else { r.exit_code = -1; r.abnormal = true; }
    return r;
}

#endif

struct TestResult { bool ran; u32 failures; double ms; };

static bool child_passes(const TestInfo& ti, const ChildResult& cr) {
    // A fatal-expected test passes iff the child terminated abnormally - the exit-2+marker
    // contract (tl_test.h TL_TEST_EXPECT_FATAL doc comment) is checked here the day tl_fatal
    // stops being a trap stub: `cr.exit_code == 2 && marker_seen`.
    //
    // TL_ASSERT compiles to `((void)0)` outside debug/dev (docs/CPP-SUBSET.md §7b): on
    // netcode/ship the call under test cannot fatal, so a TL_TEST_EXPECT_FATAL body there is
    // written to no-op and pass normally (docs/TESTING.md §9.1 fx_fatal.test.cpp's own
    // convention) - judge it as an ordinary test on those tiers, not as a fatal expectation, or
    // every fatal-expected test would fail CI outside dev by construction.
#if TL_DEV
    return ti.expect_fatal ? cr.abnormal : (!cr.abnormal && cr.exit_code == 0);
#else
    (void)ti;
    return !cr.abnormal && cr.exit_code == 0;
#endif
}

static void usage(void) {
    printf("tl_tests [--filter glob] [--tag t|!t]* [--isolate] [--workers n] [--list]\n"
           "         [--report path.tsv] [--junit path.xml] [--run-one index] [--seed n]\n");
}

int main(int argc, char** argv) {
    Selection sel = {};
    bool isolate = false;
    bool list_only = false;
    const char* report_path = nullptr;
    const char* junit_path = nullptr;
    i64 run_one = -1;
    u32 global_seed = 0;
    u32 workers = 0;

    for (int i = 1; i < argc; ++i) {
        const char* a = argv[i];
        const bool has_next = (i + 1) < argc;
        if (strcmp(a, "--filter") == 0 && has_next) { sel.filter = argv[++i]; }
        else if (strcmp(a, "--tag") == 0 && has_next) {
            const char* t = argv[++i];
            if (t[0] == '!') {
                if (sel.exclude_count == 16) { fprintf(stderr, "too many --tag exclusions\n"); return EXIT_FAIL; }
                sel.exclude[sel.exclude_count++] = t + 1;
            } else {
                if (sel.include_count == 16) { fprintf(stderr, "too many --tag selections\n"); return EXIT_FAIL; }
                sel.include[sel.include_count++] = t;
            }
        }
        else if (strcmp(a, "--isolate") == 0) { isolate = true; }
        else if (strcmp(a, "--workers") == 0 && has_next) { workers = (u32)atoi(argv[++i]); }
        else if (strcmp(a, "--list") == 0) { list_only = true; }
        else if (strcmp(a, "--report") == 0 && has_next) { report_path = argv[++i]; }
        else if (strcmp(a, "--junit") == 0 && has_next) { junit_path = argv[++i]; }
        else if (strcmp(a, "--seed") == 0 && has_next) { global_seed = (u32)strtoul(argv[++i], nullptr, 10); }
        else if (strcmp(a, "--run-one") == 0 && has_next) { run_one = atoll(argv[++i]); }
        else { usage(); return EXIT_FAIL; }
    }

    // --run-one: the child entry point. Runs the test body in-process (this IS the isolated
    // process); a fatal-expected test that actually fatals ends this process here, which is the
    // whole point (docs/TESTING.md §9.1).
    if (run_one >= 0) {
        if (run_one >= (i64)TEST_COUNT) { fprintf(stderr, "--run-one out of range\n"); return EXIT_FAIL; }
        const TestInfo& ti = TL_TESTS[run_one];
        TestCtx ctx = { ti.name, 0, 0, 0, seed_for(global_seed, (u32)run_one) };
        ti.fn(&ctx);
        return ctx.failures ? EXIT_FAIL : 0;
    }

    if (list_only) {
        for (u32 i = 0; i < TEST_COUNT; ++i) {
            if (selected(TL_TESTS[i], sel)) {
                printf("%s\t%s\t%s\t%s\n", TL_TESTS[i].name, TL_TESTS[i].tags, TL_TESTS[i].file,
                       TL_TESTS[i].expect_fatal ? "fatal" : "normal");
            }
        }
        return 0;
    }

    // Build the selected index list once - deterministic order (test_list.inc's generation
    // order, itself sorted by the tree, docs/TESTING.md §9.1).
    u32* order = (u32*)malloc(sizeof(u32) * TEST_COUNT);
    u32 order_count = 0;
    for (u32 i = 0; i < TEST_COUNT; ++i) { if (selected(TL_TESTS[i], sel)) { order[order_count++] = i; } }

    TestResult* results = (TestResult*)calloc(TEST_COUNT, sizeof(TestResult));
    char self[2048] = {0};
    self_path(self, sizeof(self));
    const char* self_exe = self[0] ? self : argv[0];

    if (workers == 0) { workers = core_count(); }
#if defined(_WIN32)
    if (workers > MAXIMUM_WAIT_OBJECTS) { workers = MAXIMUM_WAIT_OBJECTS; }   // WaitForMultipleObjects cap
#endif
    if (workers == 0) { workers = 1; }

    if (isolate) {
        // CreateProcessA's lpCurrentDirectory (and a POSIX chdir target) must be an absolute
        // path - a relative one is unreliable (the private-cwd feature silently degrading into a
        // spawn failure the wait loop then spins on was a hang found while testing this lane).
        char base_cwd[512];
#if defined(_WIN32)
        GetCurrentDirectoryA((DWORD)sizeof(base_cwd), base_cwd);
#else
        if (!getcwd(base_cwd, sizeof(base_cwd))) { base_cwd[0] = '.'; base_cwd[1] = 0; }
#endif
        char isolate_root[560];
        snprintf(isolate_root, sizeof(isolate_root), "%s/tl_isolate", base_cwd);
        make_dir(isolate_root);
        // --- the parallel pool: one child per test, up to `workers` concurrent -----------------
#if defined(_WIN32)
        ActiveChild* active = (ActiveChild*)calloc(workers, sizeof(ActiveChild));
        HANDLE* handles = (HANDLE*)calloc(workers, sizeof(HANDLE));
#else
        pid_t* active_pid = (pid_t*)calloc(workers, sizeof(pid_t));
        u32* active_idx = (u32*)calloc(workers, sizeof(u32));
        for (u32 s = 0; s < workers; ++s) { active_pid[s] = -1; }
#endif
        clock_t* slot_t0 = (clock_t*)calloc(workers, sizeof(clock_t));   // wall-clock spawn time per slot
        u32 next_job = 0;
        u32 in_flight = 0;
        char cwd[576];

        while (next_job < order_count || in_flight > 0) {
            while (in_flight < workers && next_job < order_count) {
                const u32 idx = order[next_job++];
                snprintf(cwd, sizeof(cwd), "%s/%u", isolate_root, idx);
                make_dir(cwd);
#if defined(_WIN32)
                HANDLE h = spawn_async(self_exe, idx, cwd);
                if (!h) {
                    // Spawn itself failed (never a WaitForMultipleObjects candidate - a bad
                    // handle in that array is what caused the hang this loop was built to avoid):
                    // record the failure directly, no slot consumed.
                    fprintf(stderr, "tl_tests: failed to spawn child for %s\n", TL_TESTS[idx].name);
                    results[idx].ran = true; results[idx].failures = 1u;
                    continue;
                }
                for (u32 s = 0; s < workers; ++s) {
                    if (!active[s].used) {
                        active[s].used = true; active[s].job_index = idx; active[s].process = h;
                        handles[s] = h; slot_t0[s] = clock(); ++in_flight;
                        break;
                    }
                }
#else
                pid_t pid = spawn_async_pid(self_exe, idx, cwd);
                if (pid < 0) {
                    fprintf(stderr, "tl_tests: failed to spawn child for %s\n", TL_TESTS[idx].name);
                    results[idx].ran = true; results[idx].failures = 1u;
                    continue;
                }
                for (u32 s = 0; s < workers; ++s) {
                    if (active_pid[s] < 0) {
                        active_pid[s] = pid;
                        active_idx[s] = idx; slot_t0[s] = clock(); ++in_flight;
                        break;
                    }
                }
#endif
            }
            if (in_flight == 0) { continue; }   // nothing to wait on this trip (all spawns above failed)
#if defined(_WIN32)
            // Compact the handle array to just the used slots for the wait call.
            HANDLE wait_h[MAXIMUM_WAIT_OBJECTS];
            u32 wait_slot[MAXIMUM_WAIT_OBJECTS];
            u32 wait_n = 0;
            for (u32 s = 0; s < workers; ++s) { if (active[s].used) { wait_h[wait_n] = handles[s]; wait_slot[wait_n] = s; ++wait_n; } }
            if (wait_n == 0) { continue; }
            DWORD w = WaitForMultipleObjects(wait_n, wait_h, FALSE, INFINITE);
            if (w >= WAIT_OBJECT_0 && w < WAIT_OBJECT_0 + wait_n) {
                const u32 s = wait_slot[w - WAIT_OBJECT_0];
                const u32 idx = active[s].job_index;
                ChildResult cr = reap(active[s].process);
                const TestInfo& ti = TL_TESTS[idx];
                results[idx].ran = true;
                results[idx].failures = child_passes(ti, cr) ? 0u : 1u;
                results[idx].ms = 1000.0 * (double)(clock() - slot_t0[s]) / (double)CLOCKS_PER_SEC;
                active[s].used = false;
                --in_flight;
            } else {
                // WAIT_FAILED or an unexpected return: every active handle is presumed dead
                // rather than retrying the same wait forever (the hang this loop was built to
                // avoid). Fail every in-flight job and drain the pool.
                fprintf(stderr, "tl_tests: WaitForMultipleObjects failed (%lu) - failing %u in-flight job(s)\n", GetLastError(), wait_n);
                for (u32 s = 0; s < workers; ++s) {
                    if (active[s].used) {
                        results[active[s].job_index].ran = true;
                        results[active[s].job_index].failures = 1u;
                        CloseHandle(active[s].process);
                        active[s].used = false;
                    }
                }
                in_flight = 0;
            }
#else
            int status = 0;
            pid_t done = waitpid(-1, &status, 0);
            if (done > 0) {
                for (u32 s = 0; s < workers; ++s) {
                    if (active_pid[s] == done) {
                        const u32 idx = active_idx[s];
                        ChildResult cr = reap_status(status);
                        const TestInfo& ti = TL_TESTS[idx];
                        results[idx].ran = true;
                        results[idx].failures = child_passes(ti, cr) ? 0u : 1u;
                        results[idx].ms = 1000.0 * (double)(clock() - slot_t0[s]) / (double)CLOCKS_PER_SEC;
                        active_pid[s] = -1;
                        --in_flight;
                        break;
                    }
                }
            }
#endif
        }
#if defined(_WIN32)
        free(active); free(handles);
#else
        free(active_pid); free(active_idx);
#endif
        free(slot_t0);

        // --- sorted deterministic replay of failures: re-run each failure alone, serially, in
        // ascending index order, so the report attributes clean (non-interleaved) stderr to each
        // one (docs/TESTING.md §9.1). The replay's verdict is authoritative for the report; a
        // verdict that flips between the parallel pass and the replay is a determinism-gate flake
        // (docs/TESTING.md §6 - P0, printed, not silently swallowed).
        for (u32 i = 0; i < order_count; ++i) {
            const u32 idx = order[i];
            if (results[idx].failures == 0) { continue; }
            char rcwd[576];
            snprintf(rcwd, sizeof(rcwd), "%s/%u", isolate_root, idx);
            const clock_t t0 = clock();
            ChildResult cr;
            spawn_and_wait(self_exe, idx, rcwd, &cr);
            const double ms = 1000.0 * (double)(clock() - t0) / (double)CLOCKS_PER_SEC;
            const TestInfo& ti = TL_TESTS[idx];
            const bool replay_pass = child_passes(ti, cr);
            if (replay_pass && results[idx].failures != 0) {
                fprintf(stderr, "tl_tests: %s: parallel pass FAILED, serial replay PASSED - flake, treated as FAIL (docs/TESTING.md section 6)\n", ti.name);
            }
            results[idx].ms = ms;
            results[idx].ran = true;
            // Keep the FAIL verdict even if the replay passes (P0 flake policy: never hide it).
        }
    } else {
        // --- serial: in-process for ordinary tests; a child only for fatal-expected ones -------
        for (u32 i = 0; i < order_count; ++i) {
            const u32 idx = order[i];
            const TestInfo& ti = TL_TESTS[idx];
            const clock_t t0 = clock();
            if (ti.expect_fatal) {
                ChildResult cr;
                spawn_and_wait(self_exe, idx, nullptr, &cr);
                results[idx].failures = child_passes(ti, cr) ? 0u : 1u;
            } else {
                TestCtx ctx = { ti.name, 0, 0, 0, seed_for(global_seed, idx) };
                ti.fn(&ctx);
                results[idx].failures = ctx.failures;
            }
            results[idx].ms = 1000.0 * (double)(clock() - t0) / (double)CLOCKS_PER_SEC;
            results[idx].ran = true;
        }
    }

    // --- report: always in TL_TESTS order (deterministic), TSV + JUnit + stdout summary --------
    FILE* report = report_path ? fopen(report_path, "wb") : nullptr;
    if (report_path && !report) { fprintf(stderr, "cannot write %s\n", report_path); return EXIT_FAIL; }
    if (report) { fprintf(report, "suite\ttest\tstatus\tdur_ms\tdetail\n"); }

    FILE* junit = junit_path ? fopen(junit_path, "wb") : nullptr;
    if (junit_path && !junit) { fprintf(stderr, "cannot write %s\n", junit_path); return EXIT_FAIL; }

    u32 run = 0;
    u32 failed = 0;
    double total_ms = 0.0;
    char* junit_body = (char*)malloc(1 << 20);
    usize junit_used = 0;
    junit_body[0] = 0;

    for (u32 i = 0; i < order_count; ++i) {
        const u32 idx = order[i];
        const TestInfo& ti = TL_TESTS[idx];
        const TestResult& r = results[idx];
        if (!r.ran) { continue; }
        ++run;
        total_ms += r.ms;
        char suite[128];
        suite_of(ti, suite, sizeof(suite));
        const char* status = r.failures ? "FAIL" : "PASS";
        if (r.failures) { ++failed; }
        printf("%-4s %s.%s%s (%.1f ms)\n", status, suite, ti.name, ti.expect_fatal ? " [fatal]" : "", r.ms);
        if (report) { fprintf(report, "%s\t%s\t%s\t%.3f\t%u\n", suite, ti.name, status, r.ms, r.failures); }
        if (junit) {
            const int n = snprintf(junit_body + junit_used, (1 << 20) - junit_used,
                                   "  <testcase classname=\"%s\" name=\"%s\" time=\"%.3f\">%s</testcase>\n",
                                   suite, ti.name, r.ms / 1000.0,
                                   r.failures ? "<failure message=\"see stderr\"/>" : "");
            if (n > 0 && (usize)n < (1 << 20) - junit_used) { junit_used += (usize)n; }
        }
    }

    if (junit) {
        fprintf(junit, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
                       "<testsuite name=\"tl_tests\" tests=\"%u\" failures=\"%u\" time=\"%.3f\">\n%.*s</testsuite>\n",
                run, failed, total_ms / 1000.0, (int)junit_used, junit_body);
        fclose(junit);
    }
    if (report) { fclose(report); }
    free(junit_body);
    free(order);
    free(results);

    printf("tl_tests: %u run, %u failed, %u total in the list (%.1f ms)\n", run, failed, TEST_COUNT, total_ms);
    return failed ? EXIT_FAIL : 0;
}
